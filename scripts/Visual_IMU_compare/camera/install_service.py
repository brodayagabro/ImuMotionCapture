#!/usr/bin/env python3
r"""Generate/install the RTSP camera service (also replaces an old SkellyCam unit).

Run setup.sh first, then:
  .venv/bin/python install_service.py --install \
      --server 192.168.1.90 --name cam1 --device /dev/video0 \
      --resolution 1280x720 --fps 30

Without --install, only write runtime/systemd/visual-mocap-camera-NAME.service.
With the same --name, --install replaces and restarts the existing service.
The installer uses sudo only for system installation; capture runs as a user.
"""
from __future__ import annotations

import argparse
import grp
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys
import tempfile

import camera_streamer


CAMERA_DIR = Path(__file__).resolve().parent


def unit_quote(value):
    """One systemd string, with literal specifiers (not shell quoting)."""
    value = str(value)
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("Service paths and arguments cannot contain control characters")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'


def service_account(username=None):
    try:
        if username:
            account = pwd.getpwnam(username)
        elif os.getuid() == 0 and os.environ.get("SUDO_USER"):
            account = pwd.getpwnam(os.environ["SUDO_USER"])
        else:
            account = pwd.getpwuid(os.getuid())
    except KeyError as exc:
        raise ValueError("Service user does not exist on this computer") from exc
    if account.pw_uid == 0:
        raise ValueError("Run as your camera user, or select a non-root account with --user")
    try:
        grp.getgrnam("video")
    except KeyError as exc:
        raise ValueError("Group 'video' is missing; this service requires Linux V4L2 permissions") from exc
    return account


def render_unit(camera_dir, account, stream_args, workflow="live"):
    if workflow != "live":
        raise ValueError("Camera nodes use RTSP only; select --workflow live")
    args = camera_streamer.arguments(stream_args)
    if args.list_devices or args.list_formats or args.duration is not None:
        raise ValueError("A boot service cannot use --list-devices, --list-formats or --duration")
    environment, script, stop_timeout = ".venv", "camera_streamer.py", 10
    kill_mode, description = "control-group", "RTSP streamer"
    camera_dir = Path(camera_dir).resolve()
    # Keep the venv symlink: resolving bin/python would bypass the environment.
    python = camera_dir / environment / "bin/python"
    if not python.is_file() or not os.access(python, os.X_OK):
        raise ValueError(f"Camera environment is missing: run {camera_dir / 'setup.sh'} first")
    if not (camera_dir / script).is_file():
        raise ValueError(f"Camera program is missing: {camera_dir / script}")
    if ":" in str(camera_dir):
        raise ValueError("Camera directory cannot contain ':' because it is added to PATH")
    # systemd restricts characters in the executable name, even when quoted.
    # env execs the absolute venv interpreter and permits spaces/quotes in its path.
    command = ["/usr/bin/env", str(python), "-u", str(camera_dir / script), *stream_args]
    # ':' disables systemd's $VARIABLE expansion. '%' still needs escaping.
    exec_start = " ".join(unit_quote(arg) for arg in command)
    path = f"PATH={camera_dir}/{environment}/bin:/usr/local/bin:/usr/bin:/bin"
    # WorkingDirectory takes a raw path, not a quoted argument. A trailing '/'
    # also keeps a literal trailing backslash from becoming a line continuation.
    working_directory = str(camera_dir).replace("%", "%%") + "/"
    unit = f"""# Generated by camera/install_service.py; rerun it to change settings.
[Unit]
Description=Visual MoCap camera {args.name} - {description}
Wants=network-online.target
After=network-online.target
StartLimitIntervalSec=0

[Service]
Type=simple
User={account.pw_uid}
Group={account.pw_gid}
SupplementaryGroups=video
WorkingDirectory={working_directory}
Environment={unit_quote(path)}
ExecStart=:{exec_start}
Restart=always
RestartSec=5
KillMode={kill_mode}
TimeoutStopSec={stop_timeout}
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"""
    return f"visual-mocap-camera-{args.name}.service", unit


def write_unit(directory, name, contents):
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / name
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=directory,
                                         prefix=".service-", delete=False) as output:
            temporary = Path(output.name)
            output.write(contents)
        temporary.replace(destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return destination


def install_unit(unit_file):
    if not Path("/run/systemd/system").is_dir():
        raise ValueError("Installation requires a computer booted with systemd")
    for tool in ("install", "systemctl"):
        if not shutil.which(tool):
            raise ValueError(f"Required command is missing: {tool}")
    sudo = [] if os.geteuid() == 0 else ["sudo"]
    if sudo and not shutil.which("sudo"):
        raise ValueError("sudo is missing; install the generated unit as an administrator")
    destination = Path("/etc/systemd/system") / unit_file.name
    commands = [
        ["install", "-o", "root", "-g", "root", "-m", "0644", "--", str(unit_file), str(destination)],
        ["systemctl", "daemon-reload"],
        ["systemctl", "enable", unit_file.name],
        # enable --now alone does not apply new arguments to an already running unit.
        ["systemctl", "restart", unit_file.name],
    ]
    for command in commands:
        subprocess.run([*sudo, *command], check=True)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
        epilog="Remaining options go to camera_streamer.py. "
               "The same --name replaces the existing service when used with --install.")
    parser.add_argument("--workflow", choices=("live",), default="live",
                        help="RTSP (accepted for compatibility with previous commands)")
    parser.add_argument("--install", action="store_true", help="Install, enable at boot and start/restart now")
    parser.add_argument("--user", help="Local account for capture (default: current user, or SUDO_USER)")
    options, stream_args = parser.parse_known_args(argv)
    try:
        account = service_account(options.user)
        name, contents = render_unit(CAMERA_DIR, account, stream_args, workflow=options.workflow)
        unit_file = write_unit(CAMERA_DIR / "runtime/systemd", name, contents)
        print(f"Generated: {unit_file}\nWorkflow: {options.workflow}\nCapture user: {account.pw_name}", flush=True)
        if options.install:
            install_unit(unit_file)
            print(f"Enabled at boot; start/restart requested: {name}")
        else:
            print("No service installed. Repeat with --install to install and start it.")
        print(f"Status: systemctl status {name} --no-pager\nLogs: sudo journalctl -u {name} -f")
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
